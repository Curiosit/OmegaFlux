import type { RoomDimensions, WindowSpecs } from './types';
import { score as scoreLow } from './components/OmegaFluxLow';
import { score as scoreUp } from './components/OmegaFluxUp';

export const analyticalSolidAngle = (x1: number, x2: number, z1: number, z2: number, d: number): number => {
  const dist = Math.max(d, 1e-4);
  const f = (x: number, z: number) => Math.atan2(x * z, dist * Math.sqrt(x ** 2 + dist ** 2 + z ** 2));
  return Math.abs(f(x2, z2) - f(x1, z2) - f(x2, z1) + f(x1, z1));
};

export const extractFeatures = (x: number, y: number, room: RoomDimensions, win: WindowSpecs): number[] => {
  const distF = Math.max(y, 1e-4);
  const cz = (win.sill + win.head) / 2.0;
  const h = win.head - win.sill;
  const sz = 0.8; // Sensor height

  // 1. Solid Angle
  const totalOmega = analyticalSolidAngle(
    win.center - win.width / 2 - x,
    win.center + win.width / 2 - x,
    win.sill - sz,
    win.head - sz,
    distF
  );

  // 2. Proximity & Cosine
  const d3dCent = Math.max(Math.sqrt((win.center - x) ** 2 + distF ** 2 + (cz - sz) ** 2), 0.001);
  const area = win.width * h;
  const globalCosTheta = area > 0 ? ((distF / d3dCent) * area) / area : 0;
  const globalSillClearance = sz - win.sill;

  const dx = Math.max(0, Math.abs(win.center - x) - win.width / 2);
  const dz = Math.max(0, Math.abs(cz - sz) - h / 2);
  const dmin2 = dx ** 2 + distF ** 2 + dz ** 2;
  const globalInvDmin2 = 1.0 / (dmin2 || 0.0001);

  // 3. Opaque Reflections (Bounding box estimation)
  const opaqueWallDmin = Math.min(y, room.depth - y, x, room.width - x);
  const opaqueOmega = Math.max(0, 6.28 - totalOmega); 

  return [totalOmega, globalCosTheta, globalSillClearance, globalInvDmin2, opaqueWallDmin, opaqueOmega];
};

export const predictOmegaFlux = (features: number[]): number => {
  // Get results from the two individual models
  const predLow = scoreLow(features);
  const predUp = scoreUp(features);
  
  // Calculate final result
  const udiUseful = 100.0 - predLow - predUp;
  
  return Math.max(0, Math.min(100, udiUseful));
};
